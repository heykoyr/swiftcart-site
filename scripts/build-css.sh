#!/usr/bin/env bash
# Bundles the CSS partials into css/main.css in cascade order — one request
# instead of a render-blocking @import chain. Re-run after editing any partial.
set -euo pipefail
cd "$(dirname "$0")/.."
ORDER=(
  base/tokens.css base/reset.css base/typography.css base/animations.css
  layout/grid.css layout/header.css layout/footer.css layout/sections.css
  components/buttons.css components/cards.css components/banners.css
  components/steps.css components/alerts.css components/forms.css
  components/accordions.css components/legal.css
  base/utilities.css
)
OUT=css/main.css
{
  echo "/* ============================================================"
  echo "   SwiftCart — main.css (BUNDLED, generated by scripts/build-css.sh)"
  echo "   Do NOT edit directly. Edit the partials under css/{base,layout,components}/"
  echo "   then re-run: bash scripts/build-css.sh"
  echo "   Bundling avoids the render-blocking @import waterfall."
  echo "   ============================================================ */"
  for f in "${ORDER[@]}"; do echo ""; echo "/* ── $f ─────────────────────────────────── */"; cat "css/$f"; done
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "built $OUT ($(wc -c < "$OUT") bytes from ${#ORDER[@]} partials)"
